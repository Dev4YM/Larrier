# Shown as emoji only with the variation selector.
WITH_VS16 = {
    "Symbols": [0x2764, 0x2728, 0x2B50, 0x26A1, 0x2705, 0x274C, 0x2753, 0x2757, 0x267B, 0x2622, 0x262E, 0x2618],
    "Objects": [0x2615, 0x231A, 0x23F0, 0x2699, 0x2696, 0x2702, 0x270F, 0x2712, 0x2709, 0x260E],
    "Activities": [0x26BD, 0x26BE, 0x26F3, 0x265F],
    "Travel & places": [0x2708, 0x26F5, 0x2693, 0x26FA, 0x26F2, 0x26EA],
    "Animals & nature": [0x2600, 0x2601, 0x26C5, 0x2744, 0x2614, 0x2B50],
}

lines = []
seen = set()
for ci, (cat, ranges) in enumerate(CATEGORIES):
    for a, b in ranges:
        for cp in range(a, b + 1):
            ch = chr(cp)
            if ch in seen or 0x1F3FB <= cp <= 0x1F3FF:
                continue
            try:
                name = unicodedata.name(ch).lower()
            except ValueError:
                continue
            seen.add(ch)
            lines.append((ch, name, ci))
    for cp in WITH_VS16.get(cat, []):
        ch = chr(cp) + "️"
        if ch in seen:
            continue
        try:
            name = unicodedata.name(chr(cp)).lower()
        except ValueError:
            continue
        seen.add(ch)
        lines.append((ch, name, ci))

out = ["//! Emoji for the project picker, by category, each with its Unicode name",
       "//! (for search). Generated by `app/assets/tools/build_emoji.py`; don't edit.",
       "",
       "pub const CATEGORIES: &[&str] = &[" + ", ".join(f'"{c}"' for c, _ in CATEGORIES) + "];",
       "",
       "/// (emoji, name, category)",
       "pub const EMOJI: &[(&str, &str, u8)] = &["]
for ch, name, ci in lines:
    esc = "".join(f"\\u{{{ord(c):x}}}" for c in ch)
    out.append(f'    ("{esc}", "{name}", {ci}),')
out.append("];")
out.append("")
Path("app/src/ui/emoji.rs").write_text("\n".join(out), encoding="utf-8", newline="\n")
print(len(lines), "emoji in", len(CATEGORIES), "categories")
